const fs = require('fs');
const path = require('path');

const docsDir = path.join(__dirname, '..', 'docs');
const contractPath = path.join(__dirname, 'discoverability-contract.json');
const topicsPath = path.join(docsDir, 'topics.md');
const searchPath = path.join(docsDir, 'search-and-navigation.md');
const sidebarsPath = path.join(__dirname, '..', 'sidebars.js');

const DOC_LINK_PATTERN = /\[[^\]]+\]\(([^)]+)\)/g;

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function normalize(value) {
  return value.toLowerCase().replace(/[`*_#[\]().,:/|-]+/g, ' ');
}

function assertIncludes(haystack, needle, context) {
  if (!haystack.includes(needle)) {
    throw new Error(`${context} must include ${JSON.stringify(needle)}`);
  }
}

function normalizeDocLink(href, sourcePath) {
  if (
    href.startsWith('http://') ||
    href.startsWith('https://') ||
    href.startsWith('mailto:') ||
    href.startsWith('#')
  ) {
    return null;
  }

  const withoutAnchor = href.split('#')[0].split('?')[0];
  if (!withoutAnchor) {
    return null;
  }

  if (withoutAnchor.startsWith('/docs/2.0/')) {
    return withoutAnchor.slice('/docs/2.0/'.length);
  }

  if (withoutAnchor.startsWith('/docs/')) {
    return withoutAnchor.slice('/docs/'.length);
  }

  return path.posix
    .normalize(path.posix.join(path.posix.dirname(sourcePath), withoutAnchor))
    .replace(/^\.\//, '');
}

function candidateDocPaths(relativePath) {
  if (relativePath.endsWith('.md') || relativePath.endsWith('.mdx')) {
    return [relativePath];
  }

  return [`${relativePath}.md`, `${relativePath}.mdx`, path.posix.join(relativePath, 'index.md'), path.posix.join(relativePath, 'index.mdx')];
}

function resolveDocPath(relativePath) {
  for (const candidate of candidateDocPaths(relativePath)) {
    if (fs.existsSync(path.join(docsDir, candidate))) {
      return candidate;
    }
  }

  return relativePath;
}

function extractDocLinks(markdown, sourcePath) {
  const links = new Set();
  let match;

  while ((match = DOC_LINK_PATTERN.exec(markdown)) !== null) {
    const rawLink = normalizeDocLink(match[1], sourcePath);

    if (rawLink) {
      const link = resolveDocPath(rawLink);
      links.add(link);
    }
  }

  return links;
}

function listDocIds(dir = docsDir, prefix = '') {
  const ids = [];

  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    if (entry.name.startsWith('_')) {
      continue;
    }

    const fullPath = path.join(dir, entry.name);
    const relativePath = path.posix.join(prefix, entry.name);

    if (entry.isDirectory()) {
      ids.push(...listDocIds(fullPath, relativePath));
      continue;
    }

    if (entry.isFile() && /\.(md|mdx)$/.test(entry.name)) {
      ids.push(relativePath.replace(/\.(md|mdx)$/, ''));
    }
  }

  return ids.sort();
}

function collectSidebarFacts(item, facts, parentLabel = null) {
  if (typeof item === 'string') {
    facts.docIds.push(item);
    return;
  }

  if (!item || typeof item !== 'object') {
    return;
  }

  if (item.type === 'autogenerated') {
    facts.autogenerated.push(item.dirName || '.');
    return;
  }

  if (item.type === 'doc') {
    facts.docIds.push(item.id);
    return;
  }

  if (item.type === 'category') {
    const label = item.label || parentLabel;
    facts.categories.add(label);

    for (const child of item.items || []) {
      collectSidebarFacts(child, facts, label);
    }
  }
}

function assertSidebarMatchesTaskIa(contract) {
  const sidebars = require(sidebarsPath);
  const sidebar = sidebars.tutorialSidebar || [];
  const facts = {docIds: [], categories: new Set(), autogenerated: []};

  for (const item of sidebar) {
    collectSidebarFacts(item, facts);
  }

  if (facts.autogenerated.length > 0) {
    throw new Error(
      `sidebars.js must use curated task-oriented IA, not autogenerated docs groups: ${facts.autogenerated.join(', ')}`
    );
  }

  for (const group of contract.taskGroups || []) {
    if (!facts.categories.has(group.title)) {
      throw new Error(`sidebars.js must include task-oriented category ${JSON.stringify(group.title)}`);
    }
  }

  const docIds = listDocIds();
  const sidebarDocIds = new Set(facts.docIds);
  const duplicateDocIds = facts.docIds
    .filter((docId, index) => facts.docIds.indexOf(docId) !== index)
    .sort();
  const missingDocIds = docIds.filter(docId => !sidebarDocIds.has(docId));
  const unknownDocIds = facts.docIds.filter(docId => !docIds.includes(docId)).sort();

  if (duplicateDocIds.length > 0) {
    throw new Error(`sidebars.js must not duplicate docs: ${duplicateDocIds.join(', ')}`);
  }

  if (missingDocIds.length > 0) {
    throw new Error(`sidebars.js must include every v2 doc: ${missingDocIds.join(', ')}`);
  }

  if (unknownDocIds.length > 0) {
    throw new Error(`sidebars.js references unknown docs: ${unknownDocIds.join(', ')}`);
  }
}

function assertDocExists(relativePath) {
  const resolvedPath = resolveDocPath(relativePath);
  const fullPath = path.join(docsDir, resolvedPath);

  if (!fs.existsSync(fullPath)) {
    throw new Error(`Discoverability target does not exist: docs/${relativePath}`);
  }

  return fullPath;
}

function assertTargetContentCoversQuery(query, collectionName) {
  const fullPath = assertDocExists(query.target);
  const content = normalize(read(fullPath));
  const aliases = [...query.query.split(/\s+/), ...(query.aliases || [])]
    .map(normalize)
    .map(alias => alias.trim())
    .filter(alias => alias.length >= 3);

  const covered = aliases.some(alias => content.includes(alias));

  if (!covered) {
    throw new Error(
      `${collectionName} target docs/${query.target} does not contain query language for ${JSON.stringify(query.query)}`
    );
  }
}

function assertSearchPageCoversQuery(query, search, links, collectionName) {
  const searchContent = normalize(search);
  const searchTerms = query.searchTerms || query.query.split(/\s+/);

  for (const term of searchTerms) {
    const normalizedTerm = normalize(term).trim();

    if (normalizedTerm.length >= 3 && !searchContent.includes(normalizedTerm)) {
      throw new Error(
        `docs/search-and-navigation.md must include search term ${JSON.stringify(term)} for ${collectionName} query ${JSON.stringify(query.query)}`
      );
    }
  }

  for (const link of [query.target, ...(query.related || [])]) {
    const resolvedLink = resolveDocPath(link);
    assertDocExists(resolvedLink);

    if (!links.has(resolvedLink)) {
      throw new Error(
        `docs/search-and-navigation.md must link to docs/${link} for ${collectionName} query ${JSON.stringify(query.query)}`
      );
    }
  }
}

function assertQueryCovered(query, search, links, collectionName) {
  assertTargetContentCoversQuery(query, collectionName);
  assertSearchPageCoversQuery(query, search, links, collectionName);
}

function headingPattern(title) {
  return new RegExp(`^##\\s+${title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`, 'm');
}

function assertTaskGroupsCovered(contract, topics, topicLinks) {
  const groups = contract.taskGroups || [];

  if (groups.length === 0) {
    throw new Error('Discoverability contract must include task-oriented docs groups');
  }

  for (const group of groups) {
    if (!headingPattern(group.title).test(topics)) {
      throw new Error(`docs/topics.md must include task group heading ${JSON.stringify(group.title)}`);
    }

    for (const link of group.links || []) {
      const resolvedLink = resolveDocPath(link);
      assertDocExists(resolvedLink);

      if (!topicLinks.has(resolvedLink)) {
        throw new Error(
          `docs/topics.md must link to docs/${link} for task group ${JSON.stringify(group.title)}`
        );
      }
    }
  }
}

function assertCrossReferencesCovered(contract) {
  const references = contract.crossReferences || [];

  if (references.length === 0) {
    throw new Error('Discoverability contract must include cross-reference checks');
  }

  for (const reference of references) {
    const source = resolveDocPath(reference.source);
    const fullPath = assertDocExists(source);
    const links = extractDocLinks(read(fullPath), source);

    for (const link of reference.links || []) {
      const resolvedLink = resolveDocPath(link);
      assertDocExists(resolvedLink);

      if (!links.has(resolvedLink)) {
        throw new Error(`docs/${source} must cross-link to docs/${link}`);
      }
    }
  }
}

function main() {
  const contract = JSON.parse(read(contractPath));
  const topics = read(topicsPath);
  const search = read(searchPath);
  const topicLinks = extractDocLinks(topics, 'topics.md');
  const searchLinks = extractDocLinks(search, 'search-and-navigation.md');

  assertIncludes(topics, './search-and-navigation.md', 'docs/topics.md');
  assertTaskGroupsCovered(contract, topics, topicLinks);
  assertSidebarMatchesTaskIa(contract);
  assertCrossReferencesCovered(contract);

  for (const link of contract.requiredTopicLinks || []) {
    const resolvedLink = resolveDocPath(link);
    assertDocExists(resolvedLink);
    assertIncludes(search, link, 'docs/search-and-navigation.md');
  }

  for (const query of contract.queries || []) {
    assertQueryCovered(query, search, searchLinks, 'tracked search');
  }

  const zeroResultWatchlist = contract.zeroResultWatchlist || [];
  if (zeroResultWatchlist.length === 0) {
    throw new Error('Discoverability contract must include at least one zero-result watchlist query');
  }

  assertIncludes(search, 'Zero-Result Watchlist', 'docs/search-and-navigation.md');

  for (const query of zeroResultWatchlist) {
    assertQueryCovered(query, search, searchLinks, 'zero-result watchlist');
  }

  console.log(
    `Discoverability checks passed for ${contract.queries.length} tracked queries, ${zeroResultWatchlist.length} zero-result watchlist queries, ${(contract.taskGroups || []).length} task groups, and ${(contract.crossReferences || []).length} cross-reference checks`
  );
}

main();
